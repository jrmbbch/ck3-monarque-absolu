#!/usr/bin/env pwsh
#Requires -Version 7.4
param([Alias('GamePath')][string]$EpidemicGamePath, [Alias('OutputPath')][string]$EpidemicOutputPath = (Join-Path $PSScriptRoot '../events/zz_mqa_epidemic_events.txt'))
$ErrorActionPreference='Stop'
. "$PSScriptRoot/Common.ps1"
function Get-EpidemicEventPatch([string]$Source) {
    $event=@(Get-ScriptBlocks $Source | Where-Object Key -eq 'epidemic_events.1110')
    if ($event.Count -ne 1) { throw 'Expected one epidemic_events.1110 event; review the vanilla update' }
    $original="epidemic_events.1110 = {$($event[0].Body)}"
    $match=[regex]::Match($original,'(?m)^\t\tevery_sub_realm_county = \{\n\t\t\tcustom = every_infected_county\b')
    if (-not $match.Success -or $original -notmatch 'name = epidemic_events\.1110\.b') { throw 'Expected infected-county option not found; review the vanilla update' }
    $open=$original.IndexOf('{',$match.Index); $depth=0; $end=$open
    for(;$end -lt $original.Length;$end++) {
        if($original[$end] -eq '{') { $depth++ }
        elseif($original[$end] -eq '}') { $depth--; if($depth -eq 0) { break } }
    }
    if($depth -ne 0) { throw 'Unclosed infected-county loop' }
    $loop=$original.Substring($match.Index,$end-$match.Index+1)
    $indented=($loop -split '\n' | ForEach-Object { "`t$_" }) -join "`n"
    $guard="`t`tif = {`n`t`t`tlimit = { exists = scope:epidemic_scope }`n$indented`n`t`t}"
    if ($original -match '\bid_override_priority\s*=') { throw 'Vanilla event now declares an override priority; review the vanilla update' }
    $priority="`n`tid_override_priority = 1"
    $patched=$original.Replace($loop,$guard).Insert($original.IndexOf('{')+1,$priority)
    [pscustomobject]@{ Original=$original; Patched=$patched; OriginalLoop=$loop; GuardedLoop=$guard; PriorityInsertion=$priority }
}
function Write-EpidemicFix([string]$Game,[string]$Output) {
    $source=Read-Text "$Game/events/dlc/ce1/epidemic_events.txt"
    $patch=Get-EpidemicEventPatch $source
    $header="# GENERATED by tools/generate_epidemic_fix.ps1 from the installed game.`n# Override only event 1110 at explicit priority 1 (vanilla: 0).`n# Guard its expired epidemic target before county traversal.`n# Review and regenerate after game updates. Other choices/rewards/AI weights are unchanged.`nnamespace = epidemic_events`n`n"
    Write-Text $Output ($header+$patch.Patched+"`n") -Bom
}
if ($MyInvocation.InvocationName -ne '.') { Write-EpidemicFix ($EpidemicGamePath ? $EpidemicGamePath : $script:DefaultGame) $EpidemicOutputPath }
