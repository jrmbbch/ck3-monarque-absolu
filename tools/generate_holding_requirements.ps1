#!/usr/bin/env pwsh
#Requires -Version 7.4
# Copy first-level holding requirements, without changing the large building effects file.
param([Alias('GamePath')][string]$HoldingGamePath, [Alias('OutputPath')][string]$HoldingOutputPath = (Join-Path $PSScriptRoot '../common/scripted_triggers/mqa_holding_requirements_triggers.txt'))
$ErrorActionPreference='Stop'
. "$PSScriptRoot/generate_building_effects.ps1"
function Write-HoldingRequirements([string]$Game, [string]$Output) {
    $buildings=Get-ProvinceBuildings $Game
    $lines=[Collections.Generic.List[string]]::new()
    $lines.Add('# GENERATED by tools/generate_holding_requirements.ps1 from the installed game.')
    $lines.Add('# Province scope, scope:holder = the founding ruler. Costs/time are skipped.')
    foreach ($type in @('temple','temple_citadel','city','castle')) {
        $building=$buildings["${type}_01"]
        if (-not $building) { throw "Missing holding building: ${type}_01" }
        $requirements=Get-Requirements $building
        if (-not $requirements.Trim()) { throw "Missing requirements: ${type}_01" }
        $lines.Add('')
        $lines.Add("mqa_b_can_found_${type}_trigger = {")
        foreach ($line in Format-ScriptIndent $requirements 1) { $lines.Add($line) }
        $lines.Add('}')
    }
    Write-Text $Output (($lines -join "`n")+"`n") -Bom
}
if ($MyInvocation.InvocationName -ne '.') { Write-HoldingRequirements ($HoldingGamePath ? $HoldingGamePath : $script:DefaultGame) $HoldingOutputPath }
